// Renders the UI icons from Phosphor (the icon set Kumo uses) into static SVG strings:
//   node scripts/make-ui-icons.mjs  ->  src/web/icons.ui.generated.ts
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import * as P from "@phosphor-icons/react/dist/ssr";
import { writeFile } from "node:fs/promises";

/** name -> [Phosphor icon, weight] */
const MAP = {
  success: ["CheckCircle", "fill"],
  failure: ["XCircle", "fill"],
  running: ["CircleNotch", "bold"],
  queued: ["DotsThreeCircle", "fill"],
  cancelled: ["Prohibit", "bold"],
  skipped: ["MinusCircle", "regular"],
  neutral: ["MinusCircle", "regular"],
  issueOpen: ["Record", "regular"],
  issueClosed: ["CheckCircle", "regular"],
  pr: ["GitPullRequest", "regular"],
  prMerged: ["GitMerge", "regular"],
  prClosed: ["GitPullRequest", "regular"],
  dir: ["FolderSimple", "fill"],
  file: ["File", "regular"],
  submodule: ["FolderSimpleDashed", "regular"],
  branch: ["GitBranch", "regular"],
  tag: ["Tag", "regular"],
  commit: ["GitCommit", "regular"],
  lock: ["LockSimple", "regular"],
  globe: ["Globe", "regular"],
  search: ["MagnifyingGlass", "regular"],
  bell: ["Bell", "regular"],
  plus: ["Plus", "regular"],
  gear: ["Gear", "regular"],
  play: ["PlayCircle", "regular"],
  code: ["Code", "regular"],
  comment: ["ChatCircle", "regular"],
  eye: ["Eye", "regular"],
  bot: ["Robot", "regular"],
  history: ["ClockCounterClockwise", "regular"],
  copy: ["Copy", "regular"],
  download: ["DownloadSimple", "regular"],
  edit: ["PencilSimple", "regular"],
  x: ["X", "regular"],
  check: ["Check", "regular"],
  people: ["Users", "regular"],
  key: ["Key", "regular"],
  shield: ["ShieldCheck", "regular"],
  repo: ["BookBookmark", "regular"],
  org: ["Buildings", "regular"],
  zap: ["Lightning", "regular"],
  package: ["Package", "regular"],
  upload: ["UploadSimple", "regular"],
  trash: ["Trash", "regular"],
  userPlus: ["UserPlus", "regular"],
  envelope: ["EnvelopeSimple", "regular"],
  sun: ["Sun", "regular"],
  moon: ["Moon", "regular"],
  signOut: ["SignOut", "regular"],
  caret: ["CaretDown", "regular"],
  link: ["LinkSimple", "regular"],
  rocket: ["RocketLaunch", "regular"],
  more: ["DotsThree", "bold"],
  flag: ["Flag", "regular"],
  prohibit: ["Prohibit", "regular"],
  eyeSlash: ["EyeSlash", "regular"],
};

const out = {};
for (const [name, [icon, weight]] of Object.entries(MAP)) {
  const C = P[icon] ?? P[`${icon}Icon`];
  if (!C) throw new Error(`no Phosphor icon ${icon}`);
  out[name] = renderToStaticMarkup(createElement(C, { size: 16, weight, "aria-hidden": "true", focusable: "false" }));
}
const body = Object.entries(out).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join("\n");
await writeFile(new URL("../src/web/icons.ui.generated.ts", import.meta.url), `// Generated by scripts/make-ui-icons.mjs from Phosphor icons (MIT). Do not edit.\nexport const UI_ICONS = {\n${body}\n} as const;\n`);
console.log(`${Object.keys(out).length} icons`);
