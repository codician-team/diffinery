"""Generate the favicon, app icons and social preview image.

    python3 apps/diffinery/scripts/make-icons.py

Writes apps/diffinery/src/web/icons.generated.ts (base64 PNG/ICO strings, served by
src/web/seo.ts). Needs Pillow and the Inter font (fonts-inter). Re-run after changing the
mark; the output is committed so builds don't need either.
"""
import base64
import io
import os
from PIL import Image, ImageDraw, ImageFont

ORANGE = (246, 130, 31, 255)
WHITE = (255, 255, 255, 255)
INK = (24, 24, 27, 255)
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "web", "icons.generated.ts")

# The mark (src/web/assets.ts ICONS.logo) on a 24-unit grid.
CIRCLES = [(6, 6), (6, 18), (18, 12)]
LINES = [((6, 8.5), (6, 15.5))]
CURVES = [((8.3, 7.2), (12.3, 8.2), (15.7, 9.4), (15.9, 10.5)), ((8.3, 16.8), (12.3, 15.8), (15.7, 14.6), (15.9, 13.5))]


def bezier(p0, p1, p2, p3, n=64):
    pts = []
    for i in range(n + 1):
        t = i / n
        a, b, c, d = (1 - t) ** 3, 3 * (1 - t) ** 2 * t, 3 * (1 - t) * t * t, t ** 3
        pts.append((a * p0[0] + b * p1[0] + c * p2[0] + d * p3[0], a * p0[1] + b * p1[1] + c * p2[1] + d * p3[1]))
    return pts


def draw_mark(d, ox, oy, unit, color, stroke=2.2):
    w = stroke * unit
    tx = lambda p: (ox + p[0] * unit, oy + p[1] * unit)

    def thick(points):
        # Stamp round dots along the path: wide PIL polylines leave seams on curves.
        pts = [tx(p) for p in points]
        for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
            n = max(1, int(((x1 - x0) ** 2 + (y1 - y0) ** 2) ** 0.5 / max(1, w / 8)))
            for i in range(n + 1):
                x, y = x0 + (x1 - x0) * i / n, y0 + (y1 - y0) * i / n
                d.ellipse([x - w / 2, y - w / 2, x + w / 2, y + w / 2], fill=color)

    for cx, cy in CIRCLES:
        c = tx((cx, cy))
        r = 2.5 * unit
        d.ellipse([c[0] - r - w / 2, c[1] - r - w / 2, c[0] + r + w / 2, c[1] + r + w / 2], outline=color, width=max(1, round(w)))
    for a, b in LINES:
        thick([a, b])
    for c in CURVES:
        thick(bezier(*c))


def icon(size, radius=0.22, glyph=0.8, bg=ORANGE):
    """Square icon: rounded orange tile with the white mark. radius is a fraction of the size."""
    s = 8  # supersampling
    big = size * s
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle([0, 0, big - 1, big - 1], radius=round(radius * big), fill=bg)
    unit = big * glyph / 24
    off = (big - 24 * unit) / 2
    draw_mark(d, off, off, unit, WHITE)
    return img.resize((size, size), Image.LANCZOS)


def social():
    s = 2
    w, h = 1200 * s, 630 * s
    img = Image.new("RGBA", (w, h), INK)
    d = ImageDraw.Draw(img)
    tile = icon(220 * s)
    img.alpha_composite(tile, (100 * s, (h - tile.height) // 2))
    title = ImageFont.truetype("/usr/share/fonts/opentype/inter/Inter-Bold.otf", 112 * s)
    sub = ImageFont.truetype("/usr/share/fonts/opentype/inter/Inter-Medium.otf", 40 * s)
    x = 370 * s
    d.text((x, 205 * s), "Diffinery", font=title, fill=WHITE)
    lines = ["Code hosting and CI for the agentic era.", "GitHub Actions compatible, on Cloudflare."]
    for i, line in enumerate(lines):
        d.text((x, (360 + i * 56) * s), line, font=sub, fill=(212, 212, 216, 255))
    d.text((x, 500 * s), "diffinery.com", font=sub, fill=ORANGE)
    return img.resize((1200, 630), Image.LANCZOS).convert("RGB")


def png(img):
    b = io.BytesIO()
    img.save(b, "PNG", optimize=True)
    return b.getvalue()


def ico():
    b = io.BytesIO()
    big = icon(256)
    big.save(b, "ICO", sizes=[(16, 16), (32, 32), (48, 48), (64, 64)])
    return b.getvalue()


assets = {
    "favicon.ico": ico(),
    "favicon-48.png": png(icon(48)),
    "favicon-96.png": png(icon(96)),
    "apple-touch-icon.png": png(icon(180, radius=0).convert("RGB")),
    "icon-192.png": png(icon(192)),
    "icon-512.png": png(icon(512)),
    "icon-maskable-512.png": png(icon(512, radius=0, glyph=0.62)),
    "og-image.png": png(social()),
}

with open(OUT, "w") as f:
    f.write("// Generated by scripts/make-icons.py. Do not edit.\n")
    f.write("export const ICON_FILES: Record<string, string> = {\n")
    for name, data in assets.items():
        f.write(f'  "{name}": "{base64.b64encode(data).decode()}",\n')
    f.write("};\n")
for name, data in assets.items():
    print(f"{name}: {len(data)} bytes")
