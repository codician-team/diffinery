// Builds the Shiki grammars the Worker highlights code with into text modules in build/grammars/, one JSON file
// per grammar (a grammar embedded by several languages, like JavaScript, is there once), and writes
// src/web/grammars.generated.ts, which imports them. As JavaScript the grammars would add about 3 MB to the Worker's
// main module; as text modules they are separate parts of the upload, parsed only when a file in that language is
// shown. That keeps the main module small (hosts that cap each uploaded part, like
// open-compute's 8 MiB, take it).
//
// Run by `pnpm build` and `pnpm dev`. A language added to LANGS needs no other change: src/web/highlight.ts
// takes its list from the generated file.
import { mkdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const app = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(app, "build/grammars");
const out = path.join(app, "src/web/grammars.generated.ts");

/** Shiki's names for the languages Diffinery highlights (src/web/highlight.ts maps file names and fences to them). */
const LANGS = ["astro", "bat", "c", "clojure", "cmake", "cpp", "csharp", "css", "dart", "diff", "docker", "dotenv", "elixir", "erlang", "fish", "fsharp", "go", "graphql", "groovy", "haskell", "hcl", "html", "ini", "java", "javascript", "json", "json5", "jsonc", "jsx", "julia", "kotlin", "less", "lua", "make", "markdown", "nginx", "nix", "objective-c", "ocaml", "perl", "php", "powershell", "proto", "python", "r", "ruby", "rust", "sass", "scala", "scss", "shellscript", "sql", "svelte", "swift", "terraform", "toml", "tsx", "typescript", "vue", "xml", "yaml", "zig"];

/** Each grammar's JSON by name, and each language's grammars in registration order (the ones it embeds, then its own). */
const grammars = new Map();
const order = {};
for (const lang of LANGS) {
  const { default: regs } = await import(`shiki/langs/${lang}.mjs`);
  order[lang] = [];
  for (const reg of regs) {
    const json = JSON.stringify(reg);
    if (grammars.has(reg.name) && grammars.get(reg.name) !== json) throw new Error(`grammars: two different grammars are named "${reg.name}"`);
    grammars.set(reg.name, json);
    if (!order[lang].includes(reg.name)) order[lang].push(reg.name);
  }
}

await rm(dir, { recursive: true, force: true });
await mkdir(dir, { recursive: true });
for (const [name, json] of grammars) await writeFile(path.join(dir, `${name}.txt`), json);

const names = [...grammars.keys()].sort();
const imports = names.map((n, i) => `import g${i} from "../../build/grammars/${n}.txt";`);
const texts = names.map((n, i) => `  ${JSON.stringify(n)}: g${i},`);
await writeFile(
  out,
  `// Generated by scripts/build-grammars.mjs from Shiki's grammars. Do not edit.
/* eslint-disable */
${imports.join("\n")}

export const GRAMMAR_LANGS = ${JSON.stringify(LANGS)} as const;
/** Each language's grammars in registration order: the ones it embeds, then its own. */
export const GRAMMAR_ORDER: Record<(typeof GRAMMAR_LANGS)[number], string[]> = ${JSON.stringify(order)};
/** Each grammar's JSON, by name. */
export const GRAMMAR_TEXT: Record<string, string> = {
${texts.join("\n")}
};
`,
);
const bytes = [...grammars.values()].reduce((n, j) => n + j.length, 0);
console.log(`grammars: ${LANGS.length} languages, ${grammars.size} grammars (${Math.round(bytes / 1024)} KiB)`);
