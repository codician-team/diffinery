#!/usr/bin/env node
// Render apps/diffinery/wrangler.deploy.jsonc from wrangler.jsonc plus values
// discovered by scripts/bootstrap.sh (real D1 id, Access team domain and AUD).
//
//   node scripts/render-config.mjs --d1 <uuid> [--team <x.cloudflareaccess.com>] [--aud <tag>]
//     [--public-url https://git.example.com] [--zone example.com] [--mail-from notifications@example.com]
//     [--admins you@example.com,ops@example.com]
//
// --public-url also points the Worker's route at that host (in --zone, by default
// the host's last two labels) and sends email from notifications@<host>.
// --admins sets BOOTSTRAP_ADMINS (comma-separated emails; bootstrap.sh passes what
// scripts/bootstrap-admins.sh found). Without it, wrangler.jsonc's value stays.
// From the environment it takes RUNNER_IMAGE (scripts/runner-image.sh) and
// TURNSTILE_SITE_KEY (scripts/turnstile.sh, through bootstrap).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { parseJsonc } from "./jsonc.mjs";

const { values } = parseArgs({ options: { d1: { type: "string" }, team: { type: "string" }, aud: { type: "string" }, "public-url": { type: "string" }, zone: { type: "string" }, "mail-from": { type: "string" }, admins: { type: "string" } } });
if (!values.d1) throw new Error("--d1 <database id> is required");

const appDir = join(dirname(fileURLToPath(import.meta.url)), "..", "apps", "diffinery");
const cfg = parseJsonc(readFileSync(join(appDir, "wrangler.jsonc"), "utf8"));
delete cfg.env;
delete cfg.$schema;
cfg.d1_databases[0].database_id = values.d1;
if (values.team) cfg.vars.ACCESS_TEAM_DOMAIN = values.team;
if (values.aud) cfg.vars.ACCESS_AUD = values.aud;
if (values["public-url"]) {
  const url = new URL(values["public-url"]);
  if (url.protocol !== "https:" || url.pathname !== "/") throw new Error("--public-url must be an https origin, like https://git.example.com");
  cfg.vars.PUBLIC_URL = url.origin;
  const zone = values.zone ?? url.hostname.split(".").slice(-2).join(".");
  cfg.routes = [{ pattern: `${url.hostname}/*`, zone_name: zone }];
  cfg.vars.MAIL_FROM = `notifications@${url.hostname}`;
}
if (values["mail-from"]) cfg.vars.MAIL_FROM = values["mail-from"];
if (values.admins !== undefined) {
  const admins = values.admins.split(",").map((s) => s.trim()).filter(Boolean);
  // Only verified email addresses make site administrators (src/lib/directory.ts); a login would be ignored.
  const bad = admins.filter((a) => !/^[^\s@,]+@[^\s@,]+$/.test(a));
  if (bad.length) throw new Error(`--admins takes comma-separated email addresses; not an email address: ${bad.map((b) => JSON.stringify(b)).join(", ")}`);
  cfg.vars.BOOTSTRAP_ADMINS = admins.join(",");
}
// A runner image already in the registry (scripts/runner-image.sh): containers use it
// instead of building the Dockerfile on every deploy.
if (process.env.RUNNER_IMAGE) {
  // Named as the runner reports it (`runner.image` on a job), for /meta and the Live test.
  cfg.vars.RUNNER_IMAGE = process.env.RUNNER_IMAGE.split("/").pop();
  for (const c of cfg.containers) {
    c.image = process.env.RUNNER_IMAGE;
    delete c.image_build_context;
  }
}
// The site key of the Turnstile widget scripts/turnstile.sh set up for this hostname (not a
// secret). One set in wrangler.jsonc is the operator's own and wins; turnstile.sh then leaves it alone.
if (process.env.TURNSTILE_SITE_KEY && !cfg.vars.TURNSTILE_SITE_KEY) cfg.vars.TURNSTILE_SITE_KEY = process.env.TURNSTILE_SITE_KEY;
writeFileSync(join(appDir, "wrangler.deploy.jsonc"), `// Generated by scripts/render-config.mjs; do not edit.\n${JSON.stringify(cfg, null, 2)}\n`);
console.log(`wrote ${join(appDir, "wrangler.deploy.jsonc")}`);
